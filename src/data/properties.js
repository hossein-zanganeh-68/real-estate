export function getPropertyById(id) {
  return properties.find((p) => p.id === id)
}

export function getSimilarProperties(id, count = 3) {
  const current = getPropertyById(id)
  if (!current) return []
  return properties
    .filter((p) => p.id !== id && p.type === current.type)
    .concat(properties.filter((p) => p.id !== id && p.type !== current.type))
    .slice(0, count)
}
